-- Sequences required for V2 or application use
CREATE SEQUENCE visit_code_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE vehicle_code_seq START WITH 1 INCREMENT BY 1;

-- Application Users table with TIMESTAMPTZ for created_at
CREATE TABLE app_users (
                           id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           email         VARCHAR(150) NOT NULL UNIQUE,
                           password_hash VARCHAR(100) NOT NULL,
                           full_name     VARCHAR(120) NOT NULL,
                           role          VARCHAR(30)  NOT NULL,
                           active        BOOLEAN      NOT NULL DEFAULT TRUE,
                           created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Departments table
CREATE TABLE departments (
                             id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             name VARCHAR(100) NOT NULL UNIQUE
);

-- Gates table
CREATE TABLE gates (
                       id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name   VARCHAR(50) NOT NULL UNIQUE,
                       active BOOLEAN     NOT NULL DEFAULT TRUE
);

-- Visitor Profiles table
CREATE TABLE visitor_profiles (
                                  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  full_name    VARCHAR(120) NOT NULL,
                                  phone        VARCHAR(30)  NOT NULL UNIQUE,
                                  email        VARCHAR(150),
                                  company      VARCHAR(150),
                                  photo_url    VARCHAR(500),
                                  id_proof_url VARCHAR(500),
                                  created_at   TIMESTAMP    NOT NULL DEFAULT now()
);

-- Visits table
CREATE TABLE visits (
                        id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        visit_code    VARCHAR(20)  NOT NULL UNIQUE,
                        pass_id       VARCHAR(30)  NOT NULL UNIQUE,
                        visitor_id    BIGINT       NOT NULL REFERENCES visitor_profiles (id),
                        purpose       VARCHAR(200) NOT NULL,
                        host_name     VARCHAR(120),
                        department_id BIGINT REFERENCES departments (id),
                        visit_date    DATE         NOT NULL,
                        visit_time    TIME         NOT NULL,
                        status        VARCHAR(30)  NOT NULL,
                        check_in_at   TIMESTAMP,
                        check_out_at  TIMESTAMP,
                        decided_by    VARCHAR(150),
                        decided_at    TIMESTAMP,
                        created_at    TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE INDEX idx_visits_visit_date ON visits (visit_date);
CREATE INDEX idx_visits_status     ON visits (status);
CREATE INDEX idx_visits_visitor    ON visits (visitor_id);

-- Vehicle Entries table
CREATE TABLE vehicle_entries (
                                 id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 entry_code     VARCHAR(20)  NOT NULL UNIQUE,
                                 vehicle_number VARCHAR(30)  NOT NULL,
                                 driver_name    VARCHAR(120) NOT NULL,
                                 vendor         VARCHAR(150),
                                 material       VARCHAR(150),
                                 purpose        VARCHAR(150),
                                 gate_id        BIGINT       NOT NULL REFERENCES gates (id),
                                 entry_at       TIMESTAMP    NOT NULL,
                                 exit_at        TIMESTAMP,
                                 created_at     TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE INDEX idx_vehicle_entries_entry_at ON vehicle_entries (entry_at);